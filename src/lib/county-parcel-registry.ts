/**
 * Ensures fl_county_parcel_registry table is populated and reflects real database counts.
 */
export async function ensureCountyParcelRegistrySeeded(): Promise<void> {
  const countyMetaMap = new Map(FLORIDA_COUNTIES.map((c) => [c.name.toLowerCase(), c]));

  // Get real count from fl_parcels per county
  const parcelCounts = new Map<string, number>();
  try {
    const pRows = await sql`
      SELECT county, COUNT(*)::int as count
      FROM fl_parcels
      WHERE county IS NOT NULL
      GROUP BY county
    `;
    for (const r of pRows as Array<{ county: string; count: number }>) {
      if (r.county) parcelCounts.set(r.county.toLowerCase(), Number(r.count));
    }
  } catch (err) {
    console.error("Failed querying parcel counts for registry:", err);
  }

  for (const spec of FLORIDA_PARCEL_REGISTRY_SPECS) {
    const geo = countyMetaMap.get(spec.county.toLowerCase());
    const region = geo ? geo.region : "central_florida";
    const currentCount = parcelCounts.get(spec.county.toLowerCase()) || 0;

    // Hard rule: Never mark a county "INGESTED" until its full commercial set is in the table.
    // If a county requires records request and does not have full set, keep RECORDS_REQUEST_REQUIRED.
    let status: RegistryStatus = spec.status;
    if (spec.fileFormat === "RECORDS_REQUEST_REQUIRED" && currentCount < spec.fullDepthThreshold) {
      status = "RECORDS_REQUEST_REQUIRED";
    } else if (currentCount >= spec.fullDepthThreshold) {
      status = "INGESTED";
    } else if (spec.gisDownloadUrl) {
      status = "DIRECT_DOWNLOAD";
    }

    await sql`
      INSERT INTO fl_county_parcel_registry (
        county, fips, region, population_rank, population,
        appraiser_name, official_portal_url, gis_download_url,
        file_format, field_mapping, status, records_request_procedure,
        records_request_contact, commercial_parcels_count, full_depth_threshold,
        is_priority_county, updated_at
      ) VALUES (
        ${spec.county}, ${spec.fips}, ${region}, ${spec.populationRank}, ${spec.population},
        ${spec.appraiserName}, ${spec.officialPortalUrl}, ${spec.gisDownloadUrl},
        ${spec.fileFormat}, ${JSON.stringify(DEFAULT_FIELD_MAPPING)}::jsonb, ${status},
        ${spec.recordsRequestProcedure || null}, ${spec.recordsRequestContact || null},
        ${currentCount}, ${spec.fullDepthThreshold}, FALSE, CURRENT_TIMESTAMP
      )
      ON CONFLICT (county) DO UPDATE SET
        population_rank = EXCLUDED.population_rank,
        population = EXCLUDED.population,
        appraiser_name = EXCLUDED.appraiser_name,
        official_portal_url = EXCLUDED.official_portal_url,
        gis_download_url = EXCLUDED.gis_download_url,
        file_format = EXCLUDED.file_format,
        status = EXCLUDED.status,
        records_request_procedure = EXCLUDED.records_request_procedure,
        records_request_contact = EXCLUDED.records_request_contact,
        commercial_parcels_count = ${currentCount},
        full_depth_threshold = EXCLUDED.full_depth_threshold,
        is_priority_county = EXCLUDED.is_priority_county,
        updated_at = CURRENT_TIMESTAMP
    `;
  }
}

/**
 * Returns complete registry metadata and live counts across all 67 Florida counties.
 */
export async function getCountyParcelRegistry(): Promise<CountyRegistryEntry[]> {
  await ensureCountyParcelRegistrySeeded();

  const rows = await sql`
    SELECT 
      r.county, r.fips, r.region, r.population_rank, r.population,
      r.appraiser_name, r.official_portal_url, r.gis_download_url,
      r.file_format, r.field_mapping, r.status, r.records_request_procedure,
      r.records_request_contact, r.commercial_parcels_count, r.full_depth_threshold,
      r.is_priority_county, r.last_parcels_pull_at, r.last_permits_pull_at,
      r.last_licenses_pull_at, r.last_verifications_pull_at
    FROM fl_county_parcel_registry r
    ORDER BY r.is_priority_county DESC, r.population_rank ASC
  `;

  return (rows as Array<Record<string, unknown>>).map((r) => ({
    county: String(r.county),
    fips: String(r.fips),
    region: String(r.region),
    populationRank: Number(r.population_rank),
    population: Number(r.population),
    appraiserName: String(r.appraiser_name),
    officialPortalUrl: String(r.official_portal_url),
    gisDownloadUrl: r.gis_download_url ? String(r.gis_download_url) : null,
    fileFormat: String(r.file_format),
    fieldMapping: (r.field_mapping as Record<string, string>) || DEFAULT_FIELD_MAPPING,
    status: r.status as RegistryStatus,
    recordsRequestProcedure: r.records_request_procedure ? String(r.records_request_procedure) : null,
    recordsRequestContact: r.records_request_contact ? String(r.records_request_contact) : null,
    commercialParcelsCount: Number(r.commercial_parcels_count || 0),
    fullDepthThreshold: Number(r.full_depth_threshold || 500),
    isPriorityCounty: Boolean(r.is_priority_county),
    lastParcelsPullAt: r.last_parcels_pull_at ? new Date(String(r.last_parcels_pull_at)).toISOString() : null,
    lastPermitsPullAt: r.last_permits_pull_at ? new Date(String(r.last_permits_pull_at)).toISOString() : null,
    lastLicensesPullAt: r.last_licenses_pull_at ? new Date(String(r.last_licenses_pull_at)).toISOString() : null,
    lastVerificationsPullAt: r.last_verifications_pull_at ? new Date(String(r.last_verifications_pull_at)).toISOString() : null,
  }));
}
